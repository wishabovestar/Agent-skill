# 公差分布统计
all_tols = [0.04, 0.06, 0.05, 0.10, 0.06, 0.10, 0.09, 0.07, 0.075, None, 
            5.0, 5.0, 0.18, 0.258, 0.20, 0.20, 0.35, 0.20, 0.46, 0.20,
            0.45, 0.20, 0.40, 0.20, 0.65, 0.20, 0.28, 0.20, 0.28, 0.20,
            0.35, 0.20, 0.35, 0.20]
all_tols = [t for t in all_tols if t is not None]

mean_tol = sum(all_tols) / len(all_tols)
max_tol = max(all_tols)
min_tol = min([t for t in all_tols if t > 0.01])
variance = sum((t - mean_tol)**2 for t in all_tols) / len(all_tols)
std_tol = math.sqrt(variance)

print(f"公差统计分析 (n={len(all_tols)}):")
print(f"  均值: {mean_tol:.4f}mm")
print(f"  中位数: {sorted(all_tols)[len(all_tols)//2]:.4f}mm")
print(f"  标准差: {std_tol:.4f}mm")
print(f"  最小值: {min_tol:.3f}mm (FAI3密封钉)")
print(f"  最大值: {max_tol:.1f}mm (FAI11/12极耳角度)")

# 分布
print(f"\n  分布:")
bins = [0, 0.05, 0.10, 0.15, 0.20, 0.25, 0.30, 0.35, 0.50, 5.0]
